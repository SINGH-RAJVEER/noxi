//! `noxi system init` against fixture `/proc`, `/sys` and `/dev` trees and
//! stubbed external programs. The expected files are what nixpkgs'
//! `nixos-generate-config.pl` writes for the same probes.

use std::collections::BTreeMap;
use std::fs;
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use noxi_events::Styling;
use noxi_system::init::{
	self, Distribution, Host, Options, Tools, detect, hardware_configuration, host_platform,
};

/// Stubbed programs: `btrfs subvol show` answers from `subvolumes`, and
/// fails with "not a btrfs filesystem" for other paths.
#[derive(Default)]
struct FakeTools {
	virt: String,
	lsblk: String,
	subvolumes: BTreeMap<PathBuf, String>,
}

impl Tools for FakeTools {
	fn detect_virt(&self) -> String {
		format!("{}\n", self.virt)
	}

	fn btrfs_subvol_show(&self, path: &Path) -> (bool, String) {
		match self.subvolumes.get(path) {
			Some(info) => (true, info.clone()),
			None => (
				false,
				format!("ERROR: not a btrfs filesystem: {}\n", path.display()),
			),
		}
	}

	fn bcachefs_fs_usage(&self, _: &Path) -> (bool, String) {
		(false, String::new())
	}

	fn lsblk_types(&self) -> String {
		self.lsblk.clone()
	}

	fn stratis_pool_list(&self) -> String {
		String::new()
	}
}

struct Tree {
	dir: tempfile::TempDir,
}

impl Tree {
	fn new() -> Self {
		Tree {
			dir: tempfile::tempdir().unwrap(),
		}
	}

	fn host(&self) -> Host {
		Host {
			root: self.dir.path().to_owned(),
		}
	}

	fn path(&self, path: &str) -> PathBuf {
		self.dir.path().join(path.trim_start_matches('/'))
	}

	fn write(&self, path: &str, text: &str) -> &Self {
		let path = self.path(path);
		fs::create_dir_all(path.parent().unwrap()).unwrap();
		fs::write(path, text).unwrap();
		self
	}

	fn mkdir(&self, path: &str) -> &Self {
		fs::create_dir_all(self.path(path)).unwrap();
		self
	}

	/// A symbolic link at `path` to the tree path `target`, written
	/// relative as udev and sysfs write them.
	fn link(&self, path: &str, target: &str) -> &Self {
		let link = self.path(path);
		fs::create_dir_all(link.parent().unwrap()).unwrap();
		let depth = path.trim_start_matches('/').matches('/').count();
		let relative = format!("{}{}", "../".repeat(depth), target.trim_start_matches('/'));
		symlink(relative, link).unwrap();
		self
	}

	/// A device directory with a `driver/module` link to `module`.
	fn driven(&self, path: &str, module: &str) -> &Self {
		self.mkdir(&format!("/sys/module/{module}"));
		self.link(
			&format!("{path}/driver/module"),
			&format!("/sys/module/{module}"),
		)
	}

	fn pci(&self, slot: &str, vendor: &str, device: &str, class: &str, module: Option<&str>) {
		let path = format!("/sys/bus/pci/devices/{slot}");
		self.write(&format!("{path}/vendor"), &format!("{vendor}\n"))
			.write(&format!("{path}/device"), &format!("{device}\n"))
			.write(&format!("{path}/class"), &format!("{class}\n"));
		if let Some(module) = module {
			self.driven(&path, module);
		}
	}
}

fn platform_attr() -> String {
	format!(
		"  nixpkgs.hostPlatform = lib.mkDefault \"{}\";\n",
		host_platform()
	)
}

const HEADER: &str = "# Do not modify this file!  It was generated by ‘noxi system init’\n# and may be overwritten by future invocations.  Please make changes\n# to /etc/nixos/configuration.nix instead.\n{ config, lib, pkgs, modulesPath, ... }:\n\n{\n";

/// A QEMU guest being installed to `/mnt`: virtio disks, a USB keyboard,
/// a vfat boot partition, a bind mount, a mount point with a space, a swap
/// partition, and the special and live-system mounts that must be skipped.
fn qemu_guest() -> (Tree, FakeTools) {
	let tree = Tree::new();
	tree.write(
		"/proc/cpuinfo",
		"processor\t: 0\nvendor_id\t: GenuineIntel\nflags\t\t: fpu vme vmx sse2 hypervisor\n",
	);
	tree.pci(
		"0000:00:01.2",
		"0x8086",
		"0x7020",
		"0x0c0330",
		Some("xhci_pci"),
	);
	tree.pci(
		"0000:00:04.0",
		"0x1af4",
		"0x1001",
		"0x010000",
		Some("virtio_pci"),
	);
	tree.pci(
		"0000:00:05.0",
		"0x1af4",
		"0x1004",
		"0x010000",
		Some("virtio_pci"),
	);
	// A network card: its module is not needed in the initrd.
	tree.pci(
		"0000:00:03.0",
		"0x1af4",
		"0x1000",
		"0x020000",
		Some("virtio_pci_net"),
	);
	tree.write("/sys/bus/usb/devices/1-1:1.0/bInterfaceClass", "03\n")
		.write("/sys/bus/usb/devices/1-1:1.0/bInterfaceSubClass", "01\n")
		.write("/sys/bus/usb/devices/1-1:1.0/bInterfaceProtocol", "01\n")
		.driven("/sys/bus/usb/devices/1-1:1.0", "usbhid")
		.mkdir("/sys/bus/usb/devices/usb1");
	tree.driven("/sys/class/block/vda/device", "virtio_blk")
		.mkdir("/sys/class/block/vda1");
	for device in ["vda1", "vda2", "vda3", "zram0"] {
		tree.write(&format!("/dev/{device}"), "");
	}
	tree.link("/dev/disk/by-uuid/1234", "/dev/vda1")
		.link("/dev/disk/by-uuid/swap-uuid", "/dev/vda3")
		.link("/dev/disk/by-label/BOOT", "/dev/vda2");
	tree.write(
		"/proc/swaps",
		"Filename\t\t\t\tType\t\tSize\t\tUsed\t\tPriority\n/dev/vda3                               partition\t1048572\t\t0\t\t-2\n/dev/zram0                              partition\t4194300\t\t0\t\t5\n",
	);
	for dir in [
		"/mnt/boot",
		"/mnt/data",
		"/mnt/tmp",
		"/mnt/proc",
		"/mnt/my disk",
		"/dev",
	] {
		tree.mkdir(dir);
	}
	tree.write(
		"/proc/self/mountinfo",
		"21 1 0:20 / / rw shared:1 - tmpfs tmpfs rw\n\
		 30 21 253:1 / /mnt rw,relatime shared:5 - ext4 /dev/vda1 rw\n\
		 31 30 253:2 / /mnt/boot rw,relatime shared:6 - vfat /dev/vda2 rw,fmask=0022,dmask=0022,codepage=437\n\
		 32 30 253:1 /srv/data /mnt/data rw shared:7 - ext4 /dev/vda1 rw\n\
		 33 30 0:30 / /mnt/tmp rw - tmpfs tmpfs rw\n\
		 34 30 0:31 / /mnt/proc rw - proc proc rw\n\
		 35 21 0:5 / /dev rw - devtmpfs devtmpfs rw\n\
		 36 30 253:3 / /mnt/my\\040disk rw - ext4 /dev/vdb rw\n\
		 37 30 253:9 / /mnt/gone rw - ext4 /dev/vdc rw\n",
	);
	let tools = FakeTools {
		virt: "kvm".to_owned(),
		lsblk: "TYPE\ndisk\npart\n".to_owned(),
		..FakeTools::default()
	};
	(tree, tools)
}

#[test]
fn qemu_guest_under_mnt() {
	let (tree, tools) = qemu_guest();
	let detection = detect(&tree.host(), &tools, "/mnt").unwrap();
	assert_eq!(
		hardware_configuration(&detection, false),
		format!(
			"{HEADER}  imports =\n    [ (modulesPath + \"/profiles/qemu-guest.nix\")\n    ];\n\n  boot.initrd.availableKernelModules = [ \"xhci_pci\" \"virtio_pci\" \"virtio_scsi\" \"usbhid\" \"virtio_blk\" ];\n  boot.initrd.kernelModules = [ ];\n  boot.kernelModules = [ \"kvm-intel\" ];\n  boot.extraModulePackages = [ ];\n\n  fileSystems.\"/\" =\n    {{ device = \"/dev/disk/by-uuid/1234\";\n      fsType = \"ext4\";\n    }};\n\n  fileSystems.\"/boot\" =\n    {{ device = \"/dev/disk/by-label/BOOT\";\n      fsType = \"vfat\";\n      options = [ \"fmask=0022\" \"dmask=0022\" ];\n    }};\n\n  fileSystems.\"/data\" =\n    {{ device = \"/srv/data\";\n      fsType = \"none\";\n      options = [ \"bind\" ];\n    }};\n\n  fileSystems.\"/my disk\" =\n    {{ device = \"/dev/vdb\";\n      fsType = \"ext4\";\n    }};\n\n  swapDevices =\n    [ {{ device = \"/dev/disk/by-uuid/swap-uuid\"; }}\n    ];\n\n{}}}\n",
			platform_attr()
		)
	);
	// `--no-filesystems` drops the file systems and swap devices.
	let without = hardware_configuration(&detection, true);
	assert!(!without.contains("fileSystems") && !without.contains("swapDevices"));
	assert!(without.contains("  boot.extraModulePackages = [ ];\n\n  nixpkgs.hostPlatform"));
}

#[test]
fn bare_metal_luks_btrfs_efi() {
	let tree = Tree::new();
	tree.write(
		"/proc/cpuinfo",
		"processor\t: 0\nvendor_id\t: AuthenticAMD\nflags\t\t: fpu svm sse2\nprocessor\t: 1\nvendor_id\t: AuthenticAMD\nflags\t\t: fpu svm sse2\n",
	);
	tree.pci("0000:01:00.0", "0x144d", "0xa808", "0x010802", Some("nvme"));
	tree.pci("0000:02:00.0", "0x8086", "0x4229", "0x028000", None);
	tree.pci("0000:03:00.0", "0x14e4", "0x43a3", "0x028000", None);
	tree.driven("/sys/class/block/nvme0n1/device", "nvme");
	tree.write(
		"/sys/class/block/dm-0/dm/uuid",
		"CRYPT-LUKS2-0123-cryptroot\n",
	)
	.write("/sys/class/block/dm-0/dm/name", "cryptroot\n")
	.mkdir("/sys/class/block/dm-0/slaves/nvme0n1p2");
	tree.write(
		"/sys/block/loop0/loop/backing_file",
		"/var/images/disk.img\n",
	);
	tree.mkdir("/sys/firmware/efi/efivars");
	for device in ["dm-0", "nvme0n1p1", "nvme0n1p2", "bcache0", "sdb1"] {
		tree.write(&format!("/dev/{device}"), "");
	}
	tree.link("/dev/mapper/cryptroot", "/dev/dm-0")
		.link("/dev/disk/by-uuid/ESP-UUID", "/dev/nvme0n1p1")
		.link("/dev/disk/by-uuid/luks-uuid", "/dev/nvme0n1p2");
	tree.write("/swapfile", "").write(
		"/proc/swaps",
		"Filename\t\t\t\tType\t\tSize\t\tUsed\t\tPriority\n/swapfile                               file\t\t8388604\t\t0\t\t-2\n",
	);
	for dir in [
		"/home",
		"/boot",
		"/nix/store",
		"/proc",
		"/run/user/1000",
		"/mnt/usb",
		"/var/lib/img",
	] {
		tree.mkdir(dir);
	}
	tree.write(
		"/proc/self/mountinfo",
		"25 1 254:0 /@ / rw,relatime shared:1 - btrfs /dev/mapper/cryptroot rw,subvol=/@\n\
		 26 25 254:0 /@home /home rw shared:2 - btrfs /dev/mapper/cryptroot rw,subvol=/@home\n\
		 27 25 259:1 / /boot rw - vfat /dev/nvme0n1p1 rw,fmask=0077,dmask=0077\n\
		 28 25 254:0 /@/nix/store /nix/store ro,relatime - btrfs /dev/mapper/cryptroot rw\n\
		 29 25 0:22 / /proc rw - proc proc rw\n\
		 30 25 0:45 / /run/user/1000 rw - tmpfs tmpfs rw\n\
		 31 25 0:50 / /mnt/usb rw - fuseblk /dev/sdb1 rw\n\
		 32 25 7:0 / /var/lib/img rw - ext4 /dev/loop0 rw\n",
	);
	let tools = FakeTools {
		virt: "none".to_owned(),
		lsblk: "TYPE\ndisk\ncrypt\nlvm\n".to_owned(),
		subvolumes: BTreeMap::from([
			(
				PathBuf::from("/"),
				"@\n\tName: \t\t\t@\n\tSubvolume ID: \t\t256\n".to_owned(),
			),
			(
				PathBuf::from("/home"),
				"@home\n\tName: \t\t\t@home\n\tSubvolume ID: \t\t257\n".to_owned(),
			),
		]),
	};
	let detection = detect(&tree.host(), &tools, "").unwrap();
	assert_eq!(
		detection.warnings,
		["don't know how to emit ‘fileSystem’ option for FUSE filesystem ‘/mnt/usb’"]
	);
	assert_eq!(
		hardware_configuration(&detection, false),
		format!(
			"{HEADER}  imports =\n    [ (modulesPath + \"/hardware/network/broadcom-43xx.nix\")\n      (modulesPath + \"/installer/scan/not-detected.nix\")\n    ];\n\n  boot.initrd.availableKernelModules = [ \"nvme\" \"bcache\" ];\n  boot.initrd.kernelModules = [ \"dm-snapshot\" ];\n  boot.kernelModules = [ \"kvm-amd\" ];\n  boot.extraModulePackages = [ ];\n\n  fileSystems.\"/\" =\n    {{ device = \"/dev/mapper/cryptroot\";\n      fsType = \"btrfs\";\n      options = [ \"subvol=@\" ];\n    }};\n\n  boot.initrd.luks.devices.\"cryptroot\".device = \"/dev/disk/by-uuid/luks-uuid\";\n\n  fileSystems.\"/home\" =\n    {{ device = \"/dev/mapper/cryptroot\";\n      fsType = \"btrfs\";\n      options = [ \"subvol=@home\" ];\n    }};\n\n  fileSystems.\"/boot\" =\n    {{ device = \"/dev/disk/by-uuid/ESP-UUID\";\n      fsType = \"vfat\";\n      options = [ \"fmask=0077\" \"dmask=0077\" ];\n    }};\n\n  fileSystems.\"/var/lib/img\" =\n    {{ device = \"/var/images/disk.img\";\n      fsType = \"ext4\";\n      options = [ \"loop\" ];\n    }};\n\n  swapDevices = [ ];\n\n{}  networking.enableIntel3945ABGFirmware = true;\n  hardware.cpu.amd.updateMicrocode = lib.mkDefault config.hardware.enableRedistributableFirmware;\n}}\n",
			platform_attr()
		)
	);
	let boot = init::boot_loader_config(&tree.host(), &detection.virt, init::Kernel::Lts);
	assert!(
		boot.starts_with("  # Use the systemd-boot EFI boot loader.\n"),
		"{boot}"
	);
}

#[test]
fn guests_and_md_raid() {
	let tree = Tree::new();
	tree.write(
		"/proc/cpuinfo",
		"vendor_id\t: GenuineIntel\nflags\t\t: fpu\n",
	)
	.write("/dev/md0", "")
	.write("/sys/class/block/md0/md/uuid", "x\n")
	.mkdir("/data")
	.write(
		"/proc/self/mountinfo",
		"40 1 9:0 / /data rw - ext4 /dev/md0 rw\n",
	);
	for (virt, expected) in [
		("oracle", "virtualisation.virtualbox.guest.enable = true;"),
		("parallels", "hardware.parallels.enable = true;"),
		("microsoft", "virtualisation.hypervGuest.enable = true;"),
		("systemd-nspawn", "boot.isNspawnContainer = true;"),
	] {
		let tools = FakeTools {
			virt: virt.to_owned(),
			..FakeTools::default()
		};
		let detection = detect(&tree.host(), &tools, "").unwrap();
		assert!(
			detection.attrs.iter().any(|attr| attr == expected),
			"{virt}"
		);
		// Guests get no microcode and no not-detected.nix.
		assert!(detection.imports.is_empty(), "{virt}");
		let text = hardware_configuration(&detection, false);
		assert!(
			text.contains("  boot.swraid.enable = true;\n\n\n}"),
			"{text}"
		);
	}
	let nspawn = init::boot_loader_config(&tree.host(), "systemd-nspawn", init::Kernel::Latest);
	assert_eq!(
		nspawn,
		"\n  # Use latest kernel.\n  boot.kernelPackages = pkgs.linuxPackages_latest;\n"
	);
}

fn run(tree: &Tree, options: &Options, distribution: &Distribution) -> (ExitCode, String) {
	let tools = FakeTools {
		virt: "kvm".to_owned(),
		..FakeTools::default()
	};
	let (mut out, mut err) = (Vec::new(), Vec::new());
	let code = init::run(
		options,
		&tree.host(),
		&tools,
		distribution,
		&mut out,
		&mut err,
		&Styling::PLAIN,
	);
	(code, String::from_utf8(err).unwrap())
}

#[test]
fn writes_under_the_root_and_keeps_existing_configuration() {
	let tree = Tree::new();
	tree.write("/proc/cpuinfo", "")
		.write("/proc/self/mountinfo", "");
	let target = tempfile::tempdir().unwrap();
	let root = target.path().to_str().unwrap().to_owned();
	let distribution = Distribution {
		release: "26.11".to_owned(),
		hostname: "noxios".to_owned(),
		revision: Some("e94cb152ed51bd6e24eb4a41f1460252beb52cd2".to_owned()),
	};
	let options = Options {
		root: root.clone(),
		flake: true,
		..Options::default()
	};
	let dir = target.path().join("etc/nixos");

	let (code, err) = run(&tree, &options, &distribution);
	assert_eq!(code, ExitCode::SUCCESS, "{err}");
	assert_eq!(
		err,
		format!(
			"writing {0}/hardware-configuration.nix...\nwriting {0}/flake.nix...\nwriting {0}/configuration.nix...\nFor more hardware-specific settings, see https://github.com/NixOS/nixos-hardware.\n",
			dir.display()
		)
	);
	let configuration = fs::read_to_string(dir.join("configuration.nix")).unwrap();
	assert!(
		configuration
			.starts_with("# Edit this configuration file to define what should be installed on\n")
	);
	assert!(configuration.contains("    [ # Include the results of the hardware scan.\n      ./hardware-configuration.nix\n    ];\n\n  # Use the GRUB 2 boot loader.\n  boot.loader.grub.enable = true;\n"));
	assert!(configuration.contains("\n  # Enable the X11 windowing system.\n  # services.xserver.enable = true;\n\n\n  \n\n  # Configure keymap in X11\n"));
	assert!(
		configuration
			.contains("  # networking.proxy.default = \"http://user:password@proxy:port/\";\n")
	);
	assert!(
		configuration
			.ends_with("  system.stateVersion = \"26.11\"; # Did you read the comment?\n\n}\n\n")
	);
	let flake = fs::read_to_string(dir.join("flake.nix")).unwrap();
	assert!(flake.contains("    nixpkgs.url = \"github:NixOS/nixpkgs/e94cb152ed51bd6e24eb4a41f1460252beb52cd2\";\n  };\n  outputs = inputs@{ self, nixpkgs, ... }: {\n    # NOTE: 'noxios' is the default hostname\n    nixosConfigurations.noxios = nixpkgs.lib.nixosSystem {\n      modules = [ ./configuration.nix ];\n"), "{flake}");

	// A second run regenerates the hardware configuration only.
	fs::write(dir.join("configuration.nix"), "{ edited = true; }").unwrap();
	fs::write(dir.join("flake.nix"), "{ edited = true; }").unwrap();
	fs::write(dir.join("hardware-configuration.nix"), "stale").unwrap();
	let (code, err) = run(&tree, &options, &distribution);
	assert_eq!(code, ExitCode::SUCCESS);
	assert!(err.contains(&format!(
		"warning: not overwriting existing {}/flake.nix\n",
		dir.display()
	)));
	assert!(err.contains(&format!(
		"warning: not overwriting existing {}/configuration.nix\n",
		dir.display()
	)));
	assert_eq!(
		fs::read_to_string(dir.join("configuration.nix")).unwrap(),
		"{ edited = true; }"
	);
	assert_eq!(
		fs::read_to_string(dir.join("flake.nix")).unwrap(),
		"{ edited = true; }"
	);
	assert!(
		fs::read_to_string(dir.join("hardware-configuration.nix"))
			.unwrap()
			.starts_with("# Do not modify")
	);

	// `--force` overwrites both.
	let forced = Options {
		force: true,
		..options.clone()
	};
	let (code, _) = run(&tree, &forced, &distribution);
	assert_eq!(code, ExitCode::SUCCESS);
	assert!(
		fs::read_to_string(dir.join("configuration.nix"))
			.unwrap()
			.starts_with("# Edit this")
	);
	assert!(
		fs::read_to_string(dir.join("flake.nix"))
			.unwrap()
			.starts_with("{\n  inputs = {\n")
	);

	// Without a known revision the flake follows upstream's template.
	let unpinned = init::flake("nixos", None);
	assert!(unpinned.contains(
		"    nixpkgs.url = \"https://channels.nixos.org/nixos-unstable/nixexprs.tar.zst\";\n"
	));
}

#[test]
fn show_hardware_config_writes_nothing() {
	let (tree, _) = qemu_guest();
	let tools = FakeTools {
		virt: "kvm".to_owned(),
		..FakeTools::default()
	};
	let out_dir = tempfile::tempdir().unwrap();
	let options = Options {
		root: "/mnt".to_owned(),
		dir: out_dir.path().join("cfg").to_string_lossy().into_owned(),
		show_hardware_config: true,
		..Options::default()
	};
	let (mut out, mut err) = (Vec::new(), Vec::new());
	let code = init::run(
		&options,
		&tree.host(),
		&tools,
		&Distribution::running(&tree.host()),
		&mut out,
		&mut err,
		&Styling::PLAIN,
	);
	assert_eq!(code, ExitCode::SUCCESS);
	assert!(
		String::from_utf8(out)
			.unwrap()
			.contains("fileSystems.\"/boot\"")
	);
	assert!(!out_dir.path().join("cfg").exists());
}
