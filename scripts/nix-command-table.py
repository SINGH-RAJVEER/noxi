#!/usr/bin/env python3
"""Write noxi-commands' table of `nix` commands from the reference inventory.

Reads tests/reference-inventory/cli.json (written by `just reference-inventory`)
and prints crates/noxi-commands/src/nix/table.rs: the global flags, and for
each command its gating experimental feature, flags and positional arguments.

The dump leaves out flag aliases, which CppNix registers under both names, and
the `-j` short name of `--max-jobs`, whose long entry the `max-jobs` setting's
flag replaces; ALIASES and SHORT_NAMES add them back. Run `cargo fmt` afterwards.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "tests" / "reference-inventory" / "cli.json"
OUTPUT = ROOT / "crates" / "noxi-commands" / "src" / "nix" / "table.rs"

# Flag name -> its aliases, wherever the flag is defined.
ALIASES = {
	"offline": ["no-net"],
	"ignore-env": ["ignore-environment"],
	"keep-env-var": ["keep"],
	"unset-env-var": ["unset"],
	"skip-alive": ["skip-live"],
}

# Global flags whose short name the dump loses.
SHORT_NAMES = {"max-jobs": "j"}


def rust_str(value):
	return json.dumps(value)


def rust_option(value, render=rust_str):
	return "None" if value is None else f"Some({render(value)})"


def flag_entries(flags, short_names):
	entries = []
	for name, flag in flags.items():
		short = flag["shortName"] or short_names.get(name)
		for alias in [name] + ALIASES.get(name, []):
			# An alias has no short name of its own.
			entries.append((alias, short if alias == name else None, flag))
	entries.sort(key=lambda entry: entry[0])
	lines = []
	for name, short, flag in entries:
		lines.append(
			"\t\tFlag {\n"
			f"\t\t\tname: {rust_str(name)},\n"
			f"\t\t\tshort: {rust_option(short, lambda c: repr(c))},\n"
			f"\t\t\tarity: {rust_option(flag['arity'], str)},\n"
			f"\t\t\tfeature: {rust_option(flag['experimentalFeature'])},\n"
			"\t\t},\n"
		)
	return "".join(lines)


def main():
	cli = json.loads(INVENTORY.read_text())
	out = [
		"// Generated by scripts/nix-command-table.py from tests/reference-inventory/cli.json; do not edit.\n",
		"\n",
		"use super::args::{Arg, Command, Flag};\n",
		"\n",
		"/// The flags every `nix` command accepts, sorted by name.\n",
		"pub const GLOBAL_FLAGS: &[Flag] = &[\n",
		flag_entries(cli["globalFlags"], SHORT_NAMES),
		"];\n",
		"\n",
		"/// The commands of CppNix 2.35.2's `nix`, by their words after `nix`, sorted.\n",
		"pub const COMMANDS: &[Command] = &[\n",
	]
	for path, command in sorted(cli["commands"].items()):
		args = "".join(
			"\t\t\tArg {\n"
			f"\t\t\t\tlabel: {rust_str(arg['label'])},\n"
			f"\t\t\t\tarity: {rust_option(arg['arity'], str)},\n"
			f"\t\t\t\toptional: {'true' if arg['optional'] else 'false'},\n"
			"\t\t\t},\n"
			for arg in command["args"]
		)
		flags = flag_entries(command["flags"], {})
		out.append(
			"\tCommand {\n"
			f"\t\tpath: {rust_str(path.removeprefix('nix '))},\n"
			f"\t\tfeature: {rust_option(command['experimentalFeature'])},\n"
			f"\t\tflags: &[\n{flags}\t\t],\n"
			f"\t\targs: &[\n{args}\t\t],\n"
			"\t},\n"
		)
	out.append("];\n")
	OUTPUT.write_text("".join(out))


if __name__ == "__main__":
	main()
