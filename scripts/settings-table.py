#!/usr/bin/env python3
"""Write nix-compat's table of CppNix settings from the reference inventory.

Reads tests/reference-inventory/settings.json and
tests/reference-inventory/experimental-features.json (written by
`just reference-inventory`) and prints
crates/noxi/nix-compat/src/nixcpp/settings_table.rs.

The setting type follows the JSON type of its documented default. Settings
whose default is undocumented have their CppNix type listed in TYPES below.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = ROOT / "tests" / "reference-inventory"
OUTPUT = ROOT / "crates" / "noxi" / "nix-compat" / "src" / "nixcpp" / "settings_table.rs"

# CppNix types of settings whose default the inventory records as null.
TYPES = {
	"build-dir": "String",
	"build-users-group": "String",
	"builders": "String",
	"diff-hook": "String",
	"extra-platforms": "List",
	"json-log-path": "String",
	"nix-path": "List",
	"ssl-cert-file": "String",
	"system-features": "List",
}

# Settings that accept a word besides their JSON type.
SPECIAL = {
	"max-jobs": "MaxJobs",
	"sandbox": "Sandbox",
}


def kind(name, setting):
	if name in SPECIAL:
		return SPECIAL[name]
	if name in TYPES:
		return TYPES[name]
	default = setting["defaultValue"]
	if isinstance(default, bool):
		return "Bool"
	if isinstance(default, int):
		return "Int"
	if isinstance(default, str):
		return "String"
	if isinstance(default, list):
		return "List"
	if isinstance(default, dict):
		return "Map"
	sys.exit(f"setting '{name}' needs a type in TYPES")


def main():
	settings = json.loads((INVENTORY / "settings.json").read_text())
	features = json.loads((INVENTORY / "experimental-features.json").read_text())
	lines = [
		"// Generated by scripts/settings-table.py from tests/reference-inventory/; do not edit.",
		"",
		"use super::settings::{Kind, SettingInfo};",
		"",
		"/// The settings CppNix 2.35.2 knows, sorted by name.",
		"pub(super) const SETTINGS: &[SettingInfo] = &[",
	]
	for name in sorted(settings):
		setting = settings[name]
		aliases = ", ".join(f'"{alias}"' for alias in setting["aliases"])
		feature = setting["experimentalFeature"]
		feature = f'Some("{feature}")' if feature else "None"
		lines += [
			"\tSettingInfo {",
			f'\t\tname: "{name}",',
			f"\t\taliases: &[{aliases}],",
			f"\t\tkind: Kind::{kind(name, setting)},",
			f"\t\texperimental_feature: {feature},",
			"\t},",
		]
	lines += [
		"];",
		"",
		"/// CppNix 2.35.2's experimental features, sorted.",
		"pub(super) const EXPERIMENTAL_FEATURES: &[&str] = &[",
	]
	lines += [f'\t"{feature}",' for feature in sorted(features)]
	lines += ["];", ""]
	OUTPUT.write_text("\n".join(lines))


if __name__ == "__main__":
	main()
